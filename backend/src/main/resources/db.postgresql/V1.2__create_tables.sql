-- PostgreSQL schema, equivalent to the final state of SQLite db.migration V1.0 ~ V1.2.
-- Used only when app.database.flyway-locations=classpath:db.postgresql.
-- Booleans use BOOLEAN; CREATED_AT / UPDATED_AT stay TEXT (same format as SQLite CURRENT_TIMESTAMP).
-- Identifiers are unquoted on purpose (case-insensitive access from Hibernate and named SQL).

CREATE TABLE ENDPOINT
(
    ID           VARCHAR(36)  NOT NULL,
    PUBLISH_URI  VARCHAR(100) NOT NULL,
    BEAN_NAME    VARCHAR(50)  NOT NULL,
    JAR_FILE_ID  VARCHAR(36)  NOT NULL,
    CLASS_PATH   VARCHAR(100) NOT NULL,
    IS_ACTIVE    BOOLEAN      NOT NULL DEFAULT TRUE,
    CREATED_AT   TEXT         NOT NULL DEFAULT TO_CHAR(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
    UPDATED_AT   TEXT         NOT NULL DEFAULT TO_CHAR(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
    IGNORE_CDATA BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT PK_ENDPOINT PRIMARY KEY (PUBLISH_URI)
);

CREATE TABLE JAR_FILE
(
    ID         VARCHAR(36) NOT NULL,
    NAME       VARCHAR(40) NOT NULL,
    STATUS     CHAR        NOT NULL,
    CREATED_AT TEXT        NOT NULL DEFAULT TO_CHAR(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
    UPDATED_AT TEXT        NOT NULL DEFAULT TO_CHAR(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
    CONSTRAINT PK_JAR_FILE PRIMARY KEY (ID)
);

CREATE TABLE MOCK_RESPONSE
(
    ID               VARCHAR(36)  NOT NULL,
    PUBLISH_URI      VARCHAR(100) NOT NULL,
    METHOD           VARCHAR(50)  NOT NULL,
    CONDITION        TEXT         NOT NULL,
    RESPONSE_CONTENT TEXT,
    SERVICE_TYPE     VARCHAR(15)  NOT NULL,
    IS_ACTIVE        BOOLEAN      NOT NULL DEFAULT TRUE,
    CREATED_AT       TEXT         NOT NULL DEFAULT TO_CHAR(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
    UPDATED_AT       TEXT         NOT NULL DEFAULT TO_CHAR(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
    CONSTRAINT PK_MOCK_RESPONSE PRIMARY KEY (PUBLISH_URI, METHOD, CONDITION, SERVICE_TYPE)
);

CREATE TABLE CONTROLLER
(
    ID          VARCHAR(36)  NOT NULL,
    PUBLISH_URI VARCHAR(100) NOT NULL,
    JAR_FILE_ID VARCHAR(36)  NOT NULL,
    CLASS_PATH  VARCHAR(100) NOT NULL,
    IS_ACTIVE   BOOLEAN      NOT NULL DEFAULT TRUE,
    CREATED_AT  TEXT         NOT NULL DEFAULT TO_CHAR(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
    UPDATED_AT  TEXT         NOT NULL DEFAULT TO_CHAR(CURRENT_TIMESTAMP, 'YYYY-MM-DD HH24:MI:SS'),
    CONSTRAINT PK_CONTROLLER PRIMARY KEY (PUBLISH_URI)
);
